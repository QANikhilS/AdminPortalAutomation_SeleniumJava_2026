package utils;

import java.io.File;
import java.util.Properties;

import jakarta.mail.Authenticator;
import jakarta.mail.Message;
import jakarta.mail.PasswordAuthentication;
import jakarta.mail.Session;
import jakarta.mail.Transport;
import jakarta.mail.internet.InternetAddress;
import jakarta.mail.internet.MimeBodyPart;
import jakarta.mail.internet.MimeMessage;
import jakarta.mail.internet.MimeMultipart;

	public class EmailUtils {

		public static void sendTestReport(String reportPath) 
		{

			final String senderEmail = "nikhil.shivarkar@mckinleyrice.co";
			final String appPassword = "lxssnrrbtwnzetfx";
			final String toRecipientEmail = "nikhil.shivarkar@mckinleyrice.co";
		//	final String ccRecipientEmail = "nikhil.shivarkar@mckinleyrice.co";
			

			// SMTP server properties -
			Properties prop = new Properties();
			prop.put("mail.smtp.auth", "true");
			prop.put("mail.smtp.host", "smtp.gmail.com");
			prop.put("mail.smtp.starttls.enable", "true");
			prop.put("mail.smtp.port", "587");

			
			// Create a session with Authentication of sender email- // This is from
			// jarakrta mail session.
			Session session = Session.getInstance(prop, new Authenticator() {
				protected PasswordAuthentication getPasswordAuthentication() {
					return new PasswordAuthentication(senderEmail, appPassword);
				}
			});
			session.setDebug(true);

			try {
				//Create an email message.
				Message msg = new MimeMessage(session);
				msg.setFrom(new InternetAddress(senderEmail));
				msg.setRecipients(Message.RecipientType.TO, InternetAddress.parse(toRecipientEmail));
		//		msg.setRecipients(Message.RecipientType.CC, InternetAddress.parse(ccRecipientEmail));
				msg.setSubject("Test email from QA Automation.");
				
				
				//Email body part
				MimeBodyPart textPart = new MimeBodyPart();
				textPart.setText(" Hello \n  Please find attached Test cases execution report.  \n \n[This is autogenerated email. DO NOT REPLY...]    \n \n \n Regards,  \nQA Team.");
				
				
				// Attachment part
				MimeBodyPart attachmentPart = new MimeBodyPart();
				//String filePath = System.getProperty("user.dir")+"\\reports\\ExtentReport.html";    //--- Here give the path of latest report.
				attachmentPart.attachFile(new File(reportPath));
				
				
				// Combine email body and attachment 
				MimeMultipart mimemltprt = new MimeMultipart();
				mimemltprt.addBodyPart(textPart);
				mimemltprt.addBodyPart(attachmentPart);
				msg.setContent(mimemltprt);
				
				
				// Below is for send email.
				Transport.send(msg);

				System.out.println("Email sent successfully.");

			} catch (Exception e) {
				e.printStackTrace();
			}

		}

	}

